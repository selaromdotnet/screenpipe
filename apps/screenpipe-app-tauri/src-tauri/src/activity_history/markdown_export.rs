//! Mirrors persisted Activities into one Markdown file per local day
//! (`<data dir>/activities/YYYY-MM-DD.md`) so agents and editors can read a
//! date's history without the app or its local API.
//!
//! The store remains the source of truth: files are rewritten from it after
//! every generation and once at startup, and a failed write is only logged.

use super::{overlaps, parse_time, ActivityHistoryEntry};
use chrono::{DateTime, Duration, NaiveDate, TimeZone, Utc};
use std::collections::BTreeSet;
use std::fmt::Display;
use std::path::{Path, PathBuf};

pub(super) const DIRECTORY: &str = "activities";

pub(super) fn day_path(dir: &Path, date: NaiveDate) -> PathBuf {
    dir.join(format!("{}.md", date.format("%Y-%m-%d")))
}

/// Local calendar days touched by `[start, end)`.
pub(super) fn days_in_range<Tz: TimeZone>(
    tz: &Tz,
    start: DateTime<Utc>,
    end: DateTime<Utc>,
) -> Vec<NaiveDate> {
    let first = start.with_timezone(tz).date_naive();
    let last = (end - Duration::milliseconds(1))
        .max(start)
        .with_timezone(tz)
        .date_naive();
    first.iter_days().take_while(|day| *day <= last).collect()
}

/// Every local day any entry overlaps.
pub(super) fn entry_days<Tz: TimeZone>(
    tz: &Tz,
    entries: &[ActivityHistoryEntry],
) -> BTreeSet<NaiveDate> {
    entries
        .iter()
        .filter_map(|entry| Some((parse_time(&entry.start_at)?, parse_time(&entry.end_at)?)))
        .flat_map(|(start, end)| days_in_range(tz, start, end))
        .collect()
}

/// UTC bounds of one local calendar day.
pub(super) fn day_bounds<Tz: TimeZone>(
    tz: &Tz,
    date: NaiveDate,
) -> Option<(DateTime<Utc>, DateTime<Utc>)> {
    let midnight = |day: NaiveDate| {
        tz.from_local_datetime(&day.and_hms_opt(0, 0, 0)?)
            .earliest()
            .map(|at| at.with_timezone(&Utc))
    };
    Some((midnight(date)?, midnight(date.succ_opt()?)?))
}

/// Entries overlapping `date`, ordered by start.
pub(super) fn entries_for_day<Tz: TimeZone>(
    tz: &Tz,
    date: NaiveDate,
    entries: &[ActivityHistoryEntry],
) -> Vec<ActivityHistoryEntry> {
    let Some((start, end)) = day_bounds(tz, date) else {
        return Vec::new();
    };
    let mut day: Vec<_> = entries
        .iter()
        .filter(|entry| overlaps(entry, start, end))
        .cloned()
        .collect();
    day.sort_by_key(|entry| parse_time(&entry.start_at));
    day
}

fn local_time<Tz: TimeZone>(tz: &Tz, date: NaiveDate, value: &str) -> String
where
    Tz::Offset: Display,
{
    let Some(at) = parse_time(value) else {
        return value.to_string();
    };
    let local = at.with_timezone(tz);
    if local.date_naive() == date {
        local.format("%H:%M").to_string()
    } else {
        local.format("%b %-d %H:%M").to_string()
    }
}

/// Model output is stored as single-line prose; keep it from breaking the
/// heading structure agents rely on.
fn one_line(value: &str) -> String {
    value.split_whitespace().collect::<Vec<_>>().join(" ")
}

pub(super) fn render_day<Tz: TimeZone>(
    tz: &Tz,
    date: NaiveDate,
    entries: &[ActivityHistoryEntry],
    updated_at: DateTime<Utc>,
) -> String
where
    Tz::Offset: Display,
{
    let mut out = format!(
        "# Activities — {}\n\n_Generated by screenpipe from the Activities history. Times are local ({}). Updated {}._\n",
        date.format("%Y-%m-%d (%A)"),
        updated_at.with_timezone(tz).format("UTC%:z"),
        updated_at.with_timezone(tz).format("%Y-%m-%d %H:%M"),
    );
    if entries.is_empty() {
        out.push_str("\nNo activities recorded.\n");
        return out;
    }
    for entry in entries {
        out.push_str(&format!(
            "\n## {}–{} · {}\n\n",
            local_time(tz, date, &entry.start_at),
            local_time(tz, date, &entry.end_at),
            one_line(&entry.title),
        ));
        match entry.meeting_id {
            Some(meeting_id) => out.push_str(&format!("_{} · meeting {}_\n\n", entry.kind, meeting_id)),
            None => out.push_str(&format!("_{}_\n\n", entry.kind)),
        }
        out.push_str(&one_line(&entry.summary));
        out.push('\n');
        if !entry.evidence.is_empty() {
            out.push('\n');
        }
        for evidence in &entry.evidence {
            let source = evidence
                .app_name
                .as_deref()
                .filter(|name| !name.trim().is_empty())
                .unwrap_or(&evidence.kind);
            out.push_str(&format!(
                "- {} · {} · {}\n",
                local_time(tz, date, &evidence.at),
                one_line(source),
                one_line(&evidence.label),
            ));
        }
    }
    out
}

/// Rewrite one day's file. A day with nothing to show is written only when a
/// file already exists, so a regenerated-empty day does not keep stale entries
/// while never-active days do not litter the folder.
pub(super) fn write_day<Tz: TimeZone>(
    dir: &Path,
    tz: &Tz,
    date: NaiveDate,
    entries: &[ActivityHistoryEntry],
    updated_at: DateTime<Utc>,
) -> std::io::Result<()>
where
    Tz::Offset: Display,
{
    let path = day_path(dir, date);
    if entries.is_empty() && !path.exists() {
        return Ok(());
    }
    std::fs::create_dir_all(dir)?;
    let body = render_day(tz, date, entries, updated_at);
    let temp = path.with_extension("md.tmp");
    std::fs::write(&temp, body)?;
    // `rename` replaces the destination on every platform, so readers see
    // either the previous file or the new one, never a torn write.
    std::fs::rename(&temp, &path)
}

#[cfg(test)]
mod tests {
    use super::super::ActivityHistoryEvidence;
    use super::*;
    use chrono::FixedOffset;

    fn central() -> FixedOffset {
        FixedOffset::west_opt(5 * 3600).unwrap()
    }

    fn entry(id: &str, start: &str, end: &str) -> ActivityHistoryEntry {
        ActivityHistoryEntry {
            id: id.into(),
            kind: "work".into(),
            meeting_id: None,
            start_at: start.into(),
            end_at: end.into(),
            title: format!("Title {id}"),
            summary: format!("Summary\nfor {id}"),
            evidence: vec![ActivityHistoryEvidence {
                kind: "screen".into(),
                at: start.into(),
                frame_id: Some(1),
                meeting_id: None,
                app_name: Some("Code".into()),
                label: "Edited activity_history.rs".into(),
            }],
        }
    }

    fn date(value: &str) -> NaiveDate {
        NaiveDate::parse_from_str(value, "%Y-%m-%d").unwrap()
    }

    #[test]
    fn days_follow_the_local_calendar_not_utc() {
        // 03:30Z on the 29th is still the evening of the 28th in UTC-5.
        let start = parse_time("2026-10-29T03:30:00Z").unwrap();
        let end = parse_time("2026-10-29T04:00:00Z").unwrap();
        assert_eq!(days_in_range(&central(), start, end), vec![date("2026-10-28")]);

        // Ending exactly at local midnight does not touch the next day.
        let end = parse_time("2026-10-29T05:00:00Z").unwrap();
        assert_eq!(days_in_range(&central(), start, end), vec![date("2026-10-28")]);

        let end = parse_time("2026-10-29T05:30:00Z").unwrap();
        assert_eq!(
            days_in_range(&central(), start, end),
            vec![date("2026-10-28"), date("2026-10-29")]
        );
    }

    #[test]
    fn day_selection_includes_entries_crossing_midnight_on_both_days() {
        let entries = vec![
            entry("late", "2026-10-29T04:30:00Z", "2026-10-29T05:30:00Z"),
            entry("morning", "2026-10-28T14:00:00Z", "2026-10-28T14:30:00Z"),
            entry("next", "2026-10-29T15:00:00Z", "2026-10-29T15:30:00Z"),
        ];
        let ids = |day: &str| -> Vec<String> {
            entries_for_day(&central(), date(day), &entries)
                .into_iter()
                .map(|entry| entry.id)
                .collect()
        };
        assert_eq!(ids("2026-10-28"), vec!["morning", "late"]);
        assert_eq!(ids("2026-10-29"), vec!["late", "next"]);
        assert_eq!(
            entry_days(&central(), &entries).into_iter().collect::<Vec<_>>(),
            vec![date("2026-10-28"), date("2026-10-29")]
        );
    }

    #[test]
    fn renders_local_times_and_keeps_headings_single_line() {
        let day = date("2026-10-28");
        let entries = vec![
            entry("a", "2026-10-28T14:05:00Z", "2026-10-28T14:40:00Z"),
            entry("b", "2026-10-29T04:30:00Z", "2026-10-29T05:30:00Z"),
        ];
        let updated = parse_time("2026-10-28T20:00:00Z").unwrap();
        let markdown = render_day(&central(), day, &entries, updated);
        assert!(markdown.starts_with("# Activities — 2026-10-28 (Wednesday)\n"));
        assert!(markdown.contains("Times are local (UTC-05:00). Updated 2026-10-28 15:00."));
        assert!(markdown.contains("\n## 09:05–09:40 · Title a\n\n_work_\n\nSummary for a\n\n- 09:05 · Code · Edited activity_history.rs\n"));
        assert!(markdown.contains("\n## 23:30–Oct 29 00:30 · Title b\n"));
    }

    #[test]
    fn writes_atomically_and_only_clears_days_it_already_wrote() {
        let dir = tempfile::tempdir().unwrap();
        let day = date("2026-10-28");
        let updated = parse_time("2026-10-28T20:00:00Z").unwrap();

        write_day(dir.path(), &central(), day, &[], updated).unwrap();
        assert!(!day_path(dir.path(), day).exists());

        let entries = vec![entry("a", "2026-10-28T14:05:00Z", "2026-10-28T14:40:00Z")];
        write_day(dir.path(), &central(), day, &entries, updated).unwrap();
        let written = std::fs::read_to_string(day_path(dir.path(), day)).unwrap();
        assert!(written.contains("Title a"));

        write_day(dir.path(), &central(), day, &[], updated).unwrap();
        let cleared = std::fs::read_to_string(day_path(dir.path(), day)).unwrap();
        assert!(cleared.contains("No activities recorded."));
        assert!(!cleared.contains("Title a"));
        assert_eq!(std::fs::read_dir(dir.path()).unwrap().count(), 1);
    }
}
